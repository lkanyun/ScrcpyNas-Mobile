'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const http = require('node:http')
const { webkit } = require('playwright')
// 使用真实设置脚本与合成控制表单验证保存边界 不连接设备
 test('centered mobile settings keep instant preferences separate from video saves', async t => {
  const root=path.resolve(__dirname,'../public')
  const allowed=['mobile.js','mobile.css','media-settings.js','phone-audio.js','screen-power.js']
  const server=http.createServer((req,res)=>{
    const name=req.url.slice(1)
    if(allowed.includes(name)){res.setHeader('Content-Type',name.endsWith('.css')?'text/css':'application/javascript');return res.end(fs.readFileSync(path.join(root,name)))}
    res.setHeader('Content-Type','text/html; charset=utf-8')
    res.end(`<body class="stream" style="margin:0;background:#08090d"><style>button{box-sizing:content-box;margin:4px}</style><div class="video" style="height:100vh"><div class="touch-layer"></div></div><div class="more-box" style="display:none"><div class="spoiler"><div class="box"><input value="2000000"><input value="30"><input value="1"><input value="1280"><input value="1280"><button id="native-apply">Apply</button></div></div></div><link rel="stylesheet" href="/mobile.css"><script>window.scrcpyNasRtc={};window.savedVideo=[];document.querySelector('#native-apply').onclick=()=>savedVideo.push([...document.querySelectorAll('.box input')].map(e=>e.value));window.scrcpyNasLowLatency={mount(panel){const p=document.createElement('p');p.id='media-player-status';p.textContent='WebRTC · 云中继';panel.append(p)}}</script><script src="/screen-power.js"></script><script src="/mobile.js"></script><script src="/media-settings.js"></script><script src="/phone-audio.js"></script>`)
  })
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve))
  t.after(()=>new Promise(resolve=>{server.closeAllConnections();server.close(resolve)}))
  const browser=await webkit.launch({executablePath:process.env.PHONE_AUDIO_WEBKIT_EXECUTABLE})
  t.after(()=>browser.close())
  const page=await browser.newPage({viewport:{width:393,height:852},hasTouch:true})
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  const origin='http://127.0.0.1:'+server.address().port
  await page.goto(origin+'/#!action=stream&udid=fixture')
  assert.equal(await page.locator('#mobile-orb span').innerText(),'—')
  for(const [rtt,label] of [[null,'—'],[0,'0'],[null,'—'],[99,'99'],[100,'99+'],[null,'—'],[135,'99+']]){
    await page.evaluate(rtt=>{window.scrcpyNasRtcStats={path:'direct',rtt};window.dispatchEvent(new Event('scrcpynas:quality-state'))},rtt)
    assert.equal(await page.locator('#mobile-orb span').innerText(),label)
  }
  await page.locator('#mobile-orb').evaluate(node=>node.classList.add('is-dim'))
  await page.evaluate(()=>{window.scrcpyNasRtcStats={path:'direct',rtt:140};window.dispatchEvent(new Event('scrcpynas:quality-state'))})
  assert.ok(await page.locator('#mobile-orb').evaluate(node=>node.classList.contains('is-dim')))
  await page.locator('#mobile-orb').dblclick()
  assert.ok(await page.locator('body').evaluate(node=>node.classList.contains('mobile-immersive')))
  assert.equal(await page.locator('#mobile-menu').isVisible(),false)
  await page.locator('#mobile-orb').dblclick()
  assert.equal(await page.locator('body').evaluate(node=>node.classList.contains('mobile-immersive')),false)
  assert.equal(await page.locator('#mobile-menu').isVisible(),false)
  await page.locator('#mobile-orb').click()
  await page.locator('#mobile-menu').waitFor({state:'visible'})
  assert.deepEqual(await page.locator('#mobile-menu button:visible').allTextContents(), ['返回','主页','多任务','沉浸全屏','退出全屏','更多设置'])
  for(const width of [320,375,393,430]){
    await page.setViewportSize({width,height:852})
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
    const cells=await page.locator('#mobile-menu button:visible').evaluateAll(nodes=>nodes.map(node=>({top:node.getBoundingClientRect().top,left:node.getBoundingClientRect().left,width:node.getBoundingClientRect().width,box:getComputedStyle(node).boxSizing})))
    assert.equal(cells.length,6)
    assert.equal(cells[0].top,cells[2].top)
    assert.equal(cells[3].top,cells[5].top)
    assert.ok(cells[3].top>cells[0].top)
    assert.ok(cells.every(cell=>cell.box==='border-box'&&cell.left+cell.width<=width),JSON.stringify({width,cells}))
  }
  await page.setViewportSize({width:393,height:852})
  const positions=await page.locator('#mobile-menu button:visible').evaluateAll(nodes=>nodes.map(node=>({x:node.getBoundingClientRect().x,y:node.getBoundingClientRect().y})))
  assert.equal(positions[0].y,positions[2].y)
  assert.equal(positions[3].y,positions[5].y)
  assert.ok(positions[3].y>positions[0].y)
  if(process.env.UI_SHOTS)await page.screenshot({path:path.join(process.env.UI_SHOTS,'quick-menu.png')})
  await page.locator('#mobile-menu-backdrop').click({position:{x:5,y:5}})
  assert.equal(await page.locator('#mobile-menu').isVisible(),false)
  await page.locator('#mobile-orb').click()
  await page.locator('[data-mobile-action="fullscreen"]').click()
  assert.ok(await page.locator('body').evaluate(node=>node.classList.contains('mobile-immersive')))
  await page.locator('#mobile-orb').click()
  await page.locator('[data-mobile-action="exit-fullscreen"]').click()
  assert.equal(await page.locator('body').evaluate(node=>node.classList.contains('mobile-immersive')),false)
  await page.locator('#mobile-orb').click()
  await page.locator('[data-mobile-action="settings"]').click()
  assert.equal(await page.locator('#mobile-menu-backdrop').isVisible(),false)
  for(const viewport of [{width:393,height:852},{width:375,height:667},{width:844,height:390}]){
    await page.setViewportSize(viewport)
    const card=await page.locator('#media-panel').boundingBox(),close=await page.locator('#media-close').boundingBox()
    assert.ok(Math.abs(card.x+card.width/2-viewport.width/2)<2)
    assert.ok(Math.abs(card.y+card.height/2-viewport.height/2)<2)
    assert.ok(close.y>=0 && close.y+close.height<=viewport.height)
    assert.ok(card.height<=viewport.height-30)
  }
  await page.setViewportSize({width:393,height:852})
  if(process.env.UI_SHOTS){
    await page.setViewportSize({width:375,height:667})
    await page.screenshot({path:path.join(process.env.UI_SHOTS,'settings-common.png')})
    for(const tab of ['video','details']){
      await page.locator(`[data-settings-tab=${tab}]`).click()
      await page.screenshot({path:path.join(process.env.UI_SHOTS,`settings-${tab}.png`)})
    }
    await page.locator('[data-settings-tab=common]').click()
  }
  await page.locator('#phone-audio-volume').fill('2.75')
  assert.equal(JSON.parse(await page.evaluate(()=>localStorage.getItem('scrcpyNas.audio.unity.fixture'))).volume,2.75)
  await page.locator('[data-audio-volume="0.25"]').click()
  assert.equal(await page.locator('#phone-audio-volume-value').innerText(),'25%')
  await page.locator('#media-screen-off').uncheck()
  assert.equal(await page.evaluate(()=>localStorage.getItem('scrcpyNas.screenOff.fixture')),'false')
  await page.locator('[data-settings-tab=video]').click()
  await page.locator('#media-bitrate').selectOption('1000000')
  assert.equal(await page.evaluate(()=>savedVideo.length),0)
  await page.locator('#media-close').click()
  assert.equal(await page.evaluate(()=>savedVideo.length),0)
  await page.locator('#mobile-orb').click();await page.locator('[data-mobile-action="settings"]').click()
  await page.locator('[data-settings-tab=video]').click()
  assert.equal(await page.locator('#media-bitrate').inputValue(),'2000000')
  await page.locator('[data-settings-tab=video]').click()
  await page.locator('#media-bitrate').selectOption('1000000')
  await page.locator('#media-apply').click()
  assert.equal(await page.evaluate(()=>savedVideo.length),1)
  assert.equal(JSON.parse(await page.evaluate(()=>localStorage.getItem('scrcpyNas.media.fixture'))).bitrate,1000000)
  await page.locator('#media-content').evaluate(element=>element.scrollTop=0)
  if(process.env.SETTINGS_SCREENSHOT)await page.screenshot({path:process.env.SETTINGS_SCREENSHOT})
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#media-panel').isVisible(),false)
  assert.equal(await page.locator('#media-backdrop').isVisible(),false)
  assert.deepEqual(errors,[])
 })
